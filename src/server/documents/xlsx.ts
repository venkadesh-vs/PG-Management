import 'server-only'

import type ExcelJS from 'exceljs'
import { columnKinds, countsTowardsTotal, NO_TOTALS, parseDay, prettyStatus, type Cell } from '@/lib/report-format'

/**
 * A designed Excel sheet for a list export: a title block (report, PG,
 * business, period), a styled header row with filters, fitted widths, real
 * dates and ₹ amounts, zebra rows, a totals row and a © line. Every column is
 * kept — Excel is the complete data; the PDF shows the key columns.
 */

export type SheetMeta = {
  title: string
  pgLabel: string
  business: { name: string; lines: string[] }
  context: string[]
  generatedBy: string
  company: string
}

const INK = 'FF0F172A'
const BRAND = 'FF2563EB'
const SOFT = 'FFF5F7FB'
const BRAND_SOFT = 'FFEDF2FF'
const LINE = 'FFE2E8F0'
const MUTED = 'FF64748B'

const MONEY_FMT = '"₹"#,##,##0;[Red]-"₹"#,##,##0'
const DATE_FMT = 'dd mmm yyyy'
const DATETIME_FMT = 'dd mmm yyyy, h:mm AM/PM'

/** Excel stores wall-clock time: write the Indian calendar values as if UTC. */
function asExcelDate(d: Date) {
  return new Date(Date.UTC(d.getFullYear(), d.getMonth(), d.getDate(), d.getHours(), d.getMinutes()))
}

export function addReportSheet(workbook: ExcelJS.Workbook, name: string, kind: string, header: string[], rows: Cell[][], meta: SheetMeta) {
  const kinds = columnKinds(header, rows, kind)
  const sheet = workbook.addWorksheet(name.slice(0, 31), {
    views: [{ state: 'frozen', ySplit: 0, showGridLines: false }],
    pageSetup: { orientation: 'landscape', fitToPage: true, fitToWidth: 1, fitToHeight: 0, paperSize: 9 },
  })
  const cols = Math.max(header.length, 1)
  const span = (row: number) => sheet.mergeCells(row, 1, row, Math.max(cols, 6))

  // Title block
  const title = sheet.addRow([`${meta.title}`])
  title.font = { bold: true, size: 16, color: { argb: BRAND } }
  title.height = 24
  span(title.number)
  const pg = sheet.addRow([meta.pgLabel])
  pg.font = { bold: true, size: 12, color: { argb: INK } }
  span(pg.number)
  const biz = sheet.addRow([[meta.business.name, ...meta.business.lines].filter(Boolean).join('  ·  ')])
  biz.font = { size: 10, color: { argb: MUTED } }
  span(biz.number)
  for (const line of meta.context) {
    const r = sheet.addRow([line])
    r.font = { size: 10, color: { argb: MUTED } }
    span(r.number)
  }
  const gen = sheet.addRow([`${rows.length} records · generated by ${meta.generatedBy} on ${new Date().toLocaleString('en-IN', { dateStyle: 'medium', timeStyle: 'short' })}`])
  gen.font = { size: 9, italic: true, color: { argb: MUTED } }
  span(gen.number)
  sheet.addRow([])

  // Header
  const head = sheet.addRow(header)
  head.height = 22
  head.eachCell((cell, c) => {
    const numeric = kinds[c - 1] === 'money' || kinds[c - 1] === 'number'
    cell.font = { bold: true, color: { argb: 'FFFFFFFF' }, size: 10 }
    cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: INK } }
    cell.alignment = { vertical: 'middle', wrapText: true, horizontal: numeric ? 'right' : 'left', indent: numeric ? 1 : 0 }
  })
  const headRow = head.number

  // Data
  rows.forEach((r, ri) => {
    const values = header.map((_, i) => {
      const v = r[i]
      if (v === null || v === undefined || v === '') return null
      const s = String(v)
      switch (kinds[i]) {
        case 'money':
        case 'number':
          return Number.isFinite(Number(s)) ? Number(s) : s
        case 'date':
          return /^\d{4}-\d{2}-\d{2}$/.test(s) ? asExcelDate(parseDay(s)) : s
        case 'datetime':
          return asExcelDate(new Date(s))
        case 'status':
          return prettyStatus(s)
        default:
          return s
      }
    })
    const row = sheet.addRow(values)
    row.eachCell({ includeEmpty: true }, (cell, c) => {
      const k = kinds[c - 1]
      if (k === 'money') cell.numFmt = MONEY_FMT
      if (k === 'date') cell.numFmt = DATE_FMT
      if (k === 'datetime') cell.numFmt = DATETIME_FMT
      const numeric = k === 'money' || k === 'number'
      cell.alignment = { vertical: 'top', wrapText: k === 'text', horizontal: numeric ? 'right' : 'left', indent: numeric ? 1 : 0 }
      cell.font = { size: 10, color: { argb: INK } }
      if (ri % 2 === 1) cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: SOFT } }
      cell.border = { bottom: { style: 'thin', color: { argb: LINE } } }
    })
  })

  // Totals
  const money = kinds.map((k, i) => k === 'money' && !/^(rate per unit|old rent|new rent)$/i.test(header[i]))
  if (!NO_TOTALS.has(kind) && rows.length > 1 && money.some(Boolean)) {
    const first = headRow + 1
    const last = headRow + rows.length
    const firstText = money.findIndex((m) => !m)
    // Voided / cancelled rows are listed but not added up (SUMIFS on the status column).
    const statusCol = header.findIndex((h) => /^status$/i.test(h))
    const excluded = rows.filter((r) => !countsTowardsTotal(header, r)).length
    const sumOf = (i: number) => {
      const col = sheet.getColumn(i + 1).letter
      if (statusCol < 0 || !excluded) return `SUM(${col}${first}:${col}${last})`
      const st = sheet.getColumn(statusCol + 1).letter
      const range = `${col}${first}:${col}${last}`
      const sts = `${st}${first}:${st}${last}`
      return `SUM(${range})-SUMIFS(${range},${sts},"Void*")-SUMIFS(${range},${sts},"Cancel*")-SUMIFS(${range},${sts},"Reversed")-SUMIFS(${range},${sts},"Rejected")-SUMIFS(${range},${sts},"Refunded")-SUMIFS(${range},${sts},"Checked out")-SUMIFS(${range},${sts},"Exited")`
    }
    const row = sheet.addRow(
      header.map((_, i) => (money[i] ? { formula: sumOf(i) } : i === firstText ? (excluded ? `Total (excl. ${excluded} inactive)` : 'Total') : null)),
    )
    row.eachCell({ includeEmpty: true }, (cell, c) => {
      cell.font = { bold: true, size: 10, color: { argb: money[c - 1] ? BRAND : INK } }
      cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: BRAND_SOFT } }
      if (money[c - 1]) {
        cell.numFmt = MONEY_FMT
        cell.alignment = { horizontal: 'right', indent: 1 }
      }
      cell.border = { top: { style: 'thin', color: { argb: BRAND } } }
    })
  }

  // © line
  sheet.addRow([])
  const copy = sheet.addRow([`© ${new Date().getFullYear()} ${meta.company}. All rights reserved.`])
  copy.font = { size: 9, color: { argb: MUTED } }
  span(copy.number)

  // Widths from content (dates and money fixed, text capped and wrapped)
  header.forEach((h, i) => {
    const k = kinds[i]
    const longest = Math.max(h.length, ...rows.slice(0, 500).map((r) => String(r[i] ?? '').length))
    sheet.getColumn(i + 1).width =
      k === 'date' ? 13 : k === 'datetime' ? 20 : k === 'money' ? Math.max(12, Math.min(16, longest + 4)) : Math.max(8, Math.min(45, longest + 2))
  })
  if (header.length) sheet.autoFilter = { from: { row: headRow, column: 1 }, to: { row: headRow, column: header.length } }
  sheet.views = [{ state: 'frozen', ySplit: headRow, showGridLines: false }]
  return sheet
}
